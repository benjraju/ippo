import numpy as np

# =============================================================================
# STRATEGY PARAMETERS — AutoResearch will modify these
# =============================================================================

# Minimum edge (estimated_prob - market_prob) to enter a trade
MIN_EDGE = 0.05

# Kelly fraction multiplier (0.25 = quarter Kelly)
KELLY_MULT = 0.25

# Maximum position as fraction of account
MAX_POSITION_FRAC = 0.02

# Market selection: minimum volume to consider
MIN_VOLUME = 50

# Market selection: maximum hours to settlement
MAX_HOURS = 48

# Mean-reversion parameters
MEAN_REVERT_THRESHOLD_HIGH = 0.85  # Above this, bet on reversion
MEAN_REVERT_THRESHOLD_LOW = 0.15   # Below this, bet on reversion
MEAN_REVERT_STRENGTH = 0.01  # How much to adjust probability

# Volume-weighted confidence adjustment
VOLUME_CONFIDENCE_SCALE = 200  # Volume above this = high confidence

# Spread filter: skip markets with spread above this (cents)
MAX_SPREAD = 15


# =============================================================================
# STRATEGY FUNCTIONS — AutoResearch will modify these
# =============================================================================

def estimate_probability(market_price_cents: float, volume: int, hours_left: float) -> float:
    """
    Estimate the TRUE probability of a Yes outcome.
    This is the core signal function that AutoResearch improves.

    Args:
        market_price_cents: Current yes price in cents (1-99)
        volume: Market volume in contracts
        hours_left: Hours until settlement

    Returns:
        Estimated probability (0.01 to 0.99)
    """
    market_prob = market_price_cents / 100.0

    # --- Signal 1: Mean reversion for extreme prices ---
    adjustment = 0.0
    if market_prob > MEAN_REVERT_THRESHOLD_HIGH:
        adjustment = -MEAN_REVERT_STRENGTH
    elif market_prob < MEAN_REVERT_THRESHOLD_LOW:
        adjustment = MEAN_REVERT_STRENGTH

    # --- Signal 2: Time decay adjustment ---
    # Markets closer to settlement are more efficient
    time_factor = 1.0
    if hours_left < 2:
        time_factor = 0.5  # Reduce signal near settlement
    elif hours_left > 24:
        time_factor = 1.2  # More mispricing in distant markets

    # --- Signal 3: Volume-based confidence ---
    volume_factor = min(1.0, volume / VOLUME_CONFIDENCE_SCALE)

    # Combine signals
    estimated = market_prob + (adjustment * time_factor * volume_factor)

    # Clamp to valid range
    return max(0.01, min(0.99, estimated))


def calculate_position_size(
    balance: float,
    estimated_prob: float,
    market_price_cents: float,
) -> int:
    """
    Calculate number of contracts to trade.
    Uses fractional Kelly criterion with safety caps.

    Returns:
        Number of contracts (0 if no trade)
    """
    market_prob = market_price_cents / 100.0
    edge = estimated_prob - market_prob

    # Must have minimum edge
    if abs(edge) < MIN_EDGE:
        return 0

    # Kelly criterion: f* = (b*p - q) / b
    if market_prob <= 0 or market_prob >= 1:
        return 0

    b = (1 - market_prob) / market_prob  # Odds
    q = 1 - estimated_prob

    kelly = (b * estimated_prob - q) / b
    if kelly <= 0:
        return 0

    # Apply Kelly multiplier and position cap
    size_frac = min(kelly * KELLY_MULT, MAX_POSITION_FRAC)
    dollars = balance * size_frac

    # Convert to contracts
    cost_per_contract = market_price_cents / 100.0
    if cost_per_contract <= 0:
        return 0

    contracts = int(dollars / cost_per_contract)
    return max(0, contracts)


def should_trade(
    market_price_cents: float,
    volume: int,
    hours_left: float,
    spread: float,
) -> bool:
    """
    Market filter: should we even consider this market?

    Returns:
        True if market passes all filters
    """
    if volume < MIN_VOLUME:
        return False
    if hours_left > MAX_HOURS:
        return False
    if hours_left < 0.5:  # Too close to settlement
        return False
    if spread > MAX_SPREAD:
        return False
    if market_price_cents < 3 or market_price_cents > 97:
        return False  # Skip extreme prices
    return True


def get_strategy_params() -> dict:
    """Return current strategy parameters for logging."""
    return {
        "min_edge": MIN_EDGE,
        "kelly_mult": KELLY_MULT,
        "max_position_frac": MAX_POSITION_FRAC,
        "min_volume": MIN_VOLUME,
        "max_hours": MAX_HOURS,
        "mean_revert_high": MEAN_REVERT_THRESHOLD_HIGH,
        "mean_revert_low": MEAN_REVERT_THRESHOLD_LOW,
        "mean_revert_strength": MEAN_REVERT_STRENGTH,
        "volume_confidence_scale": VOLUME_CONFIDENCE_SCALE,
        "max_spread": MAX_SPREAD,
    }
